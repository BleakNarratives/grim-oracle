#!/usr/bin/env python3
"""grim_serve.py -- local HTTP shell around oracle.simulate. Stdlib only.

The browser never holds a key and never calls a provider. This process does
both. That is the whole reason the page can run outside a hosted chat product.

Binds 127.0.0.1 only, and refuses POSTs whose Origin is not local, so a page on
the internet cannot spend this machine's credits.

Usage:  python3 grim_serve.py [--provider groq|gemini|offline] [--mode civil|cannibal]
        [--port 8787] [--open]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import webbrowser
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

REPO = Path(__file__).resolve().parent
sys.path.insert(0, str(REPO))
import oracle  # noqa: E402
import providers  # noqa: E402

PAGE = REPO / "Grim" / "grim_market_sim.html"
MAX_BODY = 64_000
LOCAL_HOSTS = ("127.0.0.1", "localhost", "[::1]")

# ── the client contract ────────────────────────────────────────────────────
# One shape, four answers a client can act on: what it asked, what came back,
# which model produced it, why that model, and the floor text to show when no
# model answers at all. A client must never need to import this module to know
# whether the answer is real -- that is what routing_reason is for.
CONTRACT_FIELDS = ("prompt", "response_text", "model_used",
                   "routing_reason", "offline_text")

# Order matters and is deliberate: the cheapest verified provider first, then
# the OpenAI-compatible key, then Gemini, then the floor. A provider absent
# from this list can still serve the page; it cannot join the cascade.
CASCADE_ORDER = ("groq", "deepseek", "gemini")


def offline_text(prompt: str) -> str:
    """The floor. Never presented as a model answer, never generated by one."""
    digest = hashlib.sha256((prompt or "").encode()).hexdigest()[:8]
    return (f"OFFLINE — no model answered. This text was not generated by a "
            f"model.\nThe prompt stayed on this machine ({len(prompt or '')} "
            f"chars, sha256 {digest}).")


def build_contract(prompt: str, response_text: str, model_used: str,
                   routing_reason: str, floor: str | None = None) -> dict:
    return {
        "prompt": prompt,
        "response_text": response_text,
        "model_used": model_used,
        "routing_reason": routing_reason,
        "offline_text": floor if floor is not None else offline_text(prompt),
    }


def validate_contract(obj: object) -> list[str]:
    """Return a list of problems; empty means the shape is honoured.

    A client uses this to refuse to render a half-answer: a response missing
    routing_reason is a response nobody can audit.
    """
    if not isinstance(obj, dict):
        return ["contract must be an object"]
    problems = [f"missing {k}" for k in CONTRACT_FIELDS if k not in obj]
    problems += [f"not a string: {k}" for k in CONTRACT_FIELDS
                 if k in obj and not isinstance(obj[k], str)]
    return problems


def cascade_ask(prompt: str, asks: dict) -> dict:
    """Try each provider in insertion order; fall to the floor if all fail.

    `asks` maps provider -> ask(prompt)->str, injected so this is testable
    without a network. A provider that raises is recorded and skipped, not
    surfaced: the client gets a usable answer or a labelled floor, never a
    dead screen. That is the whole point of the cascade.
    """
    tried: list[str] = []
    for provider, ask in asks.items():
        try:
            text = ask(prompt)
        except (RuntimeError, ValueError, OSError) as exc:
            tried.append(f"{provider}: {str(exc)[:70]}")
            continue
        if not text or not str(text).strip():
            tried.append(f"{provider}: empty response")
            continue
        model = providers.last_model_used() or providers.default_model(provider)
        reason = f"answered by {provider}"
        if tried:
            reason += "; fell through from " + " | ".join(tried)
        return build_contract(prompt, str(text), model, reason)

    reason = ("all providers failed: " + " | ".join(tried)) if tried else \
             "no provider configured"
    return build_contract(prompt, offline_text(prompt), "offline", reason)


def build_asks(primary: str) -> dict:
    """provider -> ask(), primary first, then the rest of the cascade.

    Only providers that report ready are included: an unready provider in the
    chain would spend a timeout on every request to learn what provider_status
    already knew.
    """
    order = ([primary] if primary in CASCADE_ORDER else []) + \
            [p for p in CASCADE_ORDER if p != primary]
    asks = {}
    for name in order:
        try:
            if providers.provider_status(name)["ready"]:
                asks[name] = providers.get_ask(name)
        except (ValueError, RuntimeError, OSError):
            continue
    return asks


def make_handler(provider: str, model: str, default_mode: str):
    ask = providers.get_ask(provider, model)
    cascade = build_asks(provider)

    class Handler(BaseHTTPRequestHandler):
        server_version = "grim-oracle/1.0"

        def log_message(self, fmt, *args):
            sys.stderr.write("grim_serve: " + (fmt % args) + "\n")

        def _send(self, code: int, body: bytes, ctype: str) -> None:
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("X-Content-Type-Options", "nosniff")
            self.end_headers()
            self.wfile.write(body)

        def _json(self, code: int, obj: dict) -> None:
            self._send(code, json.dumps(obj).encode(), "application/json; charset=utf-8")

        def _local_origin(self) -> bool:
            origin = self.headers.get("Origin")
            if not origin:
                return True
            return origin.startswith("http://") and any(h in origin for h in LOCAL_HOSTS)

        def _handle_ask(self) -> None:
            """The frozen contract. Answers 200 even when every model failed:
            the floor is part of the response, so a client that trusts
            routing_reason never has to guess whether text is real."""
            if not self._local_origin():
                self._json(403, {"error": "cross-origin request refused"})
                return
            try:
                length = int(self.headers.get("Content-Length") or 0)
            except ValueError:
                length = 0
            if length <= 0 or length > MAX_BODY:
                self._json(413, {"error": "missing or oversized body"})
                return
            try:
                payload = json.loads(self.rfile.read(length).decode("utf-8"))
                prompt = str((payload or {}).get("prompt") or "").strip()
            except (ValueError, UnicodeDecodeError, AttributeError) as e:
                self._json(400, {"error": f"bad request: {e}"})
                return
            if not prompt:
                self._json(422, {"error": "prompt is empty"})
                return
            if len(prompt) > 4000:
                self._json(422, {"error": "prompt too long (max 4000 chars)"})
                return
            self._json(200, cascade_ask(prompt, cascade))

        def do_GET(self):  # noqa: N802 - stdlib naming
            if self.path in ("/", "/index.html", "/grim_market_sim.html"):
                try:
                    self._send(200, PAGE.read_bytes(), "text/html; charset=utf-8")
                except OSError:
                    self._json(500, {"error": f"cannot read {PAGE.name}"})
            elif self.path == "/api/health":
                status = providers.provider_status(provider)
                self._json(200, {"ok": True, "mode": default_mode,
                                 "model": model or providers.default_model(provider),
                                 "ladder": providers.model_candidates(provider), **status})
            else:
                self._json(404, {"error": "not found"})

        def do_POST(self):  # noqa: N802 - stdlib naming
            if self.path == "/api/ask":
                self._handle_ask()
                return
            if self.path != "/api/simulate":
                self._json(404, {"error": "not found"})
                return
            if not self._local_origin():
                self._json(403, {"error": "cross-origin request refused"})
                return
            try:
                length = int(self.headers.get("Content-Length") or 0)
            except ValueError:
                length = 0
            if length <= 0 or length > MAX_BODY:
                self._json(413, {"error": "missing or oversized body"})
                return
            try:
                payload = json.loads(self.rfile.read(length).decode("utf-8"))
                if not isinstance(payload, dict):
                    raise ValueError("body must be an object")
            except (ValueError, UnicodeDecodeError) as e:
                self._json(400, {"error": f"bad request: {e}"})
                return

            payload.setdefault("mode", default_mode)
            payload["_provider"] = provider
            payload["_model"] = model or providers.default_model(provider)
            payload["_demo"] = provider == "offline"
            pitch = str(payload.get("pitch") or "")
            if not payload["_demo"]:
                clean, redacted = providers.redact(pitch)
                payload["pitch"] = clean
            else:
                redacted = 0

            try:
                out = oracle.simulate(payload, ask)
                out["meta"]["redacted_secrets"] = redacted
                # The ladder may have fallen through to another model; report
                # what actually answered rather than what we asked for.
                out["meta"]["model_actual"] = (providers.last_model_used()
                                               or out["meta"].get("model", ""))
                self._json(200, {"ok": True, "data": out})
            except ValueError as e:
                self._json(422, {"ok": False, "error": str(e)})
            except RuntimeError as e:
                self._json(502, {"ok": False, "error": str(e)})

    return Handler


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Serve GRIM Oracle locally.")
    ap.add_argument("--provider", choices=["groq", "gemini", "offline"], default="groq")
    ap.add_argument("--mode", choices=list(oracle.MODES), default="civil")
    ap.add_argument("--model", default="")
    ap.add_argument("--port", type=int, default=8787)
    ap.add_argument("--open", action="store_true", help="open the page in a browser")
    ap.add_argument("--no-log", action="store_true",
                    help="do not append to logs/calls.jsonl")
    ap.add_argument("--doctor", action="store_true",
                    help="report provider readiness and exit; sends nothing")
    a = ap.parse_args(argv)
    if a.doctor:
        report = providers.doctor()
        print(json.dumps(report, indent=2))
        return 0 if not report["warnings"] else 1
    if a.no_log:
        import os
        os.environ["GRIM_NO_LOG"] = "1"

    # Empty model means "walk the ladder"; an explicit one pins a single model.
    model = a.model
    if not PAGE.is_file():
        print(f"grim_serve: page missing: {PAGE}", file=sys.stderr)
        return 2
    status = providers.provider_status(a.provider)
    if not status["ready"]:
        print(f"grim_serve: {a.provider} is not ready ({status['note']}).",
              file=sys.stderr)
        print("grim_serve: try --provider offline for canned demo data.",
              file=sys.stderr)
        return 2

    url = f"http://127.0.0.1:{a.port}/"
    srv = ThreadingHTTPServer(("127.0.0.1", a.port),
                              make_handler(a.provider, model, a.mode))
    shown = model or providers.default_model(a.provider)
    ladder = providers.model_candidates(a.provider) if a.provider != "offline" else []
    print(f"grim_serve: {url}  provider={a.provider} model={shown} mode={a.mode}")
    if ladder:
        print(f"grim_serve: fallback ladder: {' -> '.join(ladder)}")
    print("grim_serve: keys stay on this machine; the browser never receives one.")
    if a.provider == "offline":
        print("grim_serve: OFFLINE DEMO -- canned data, your input is ignored.")
    if a.open:
        webbrowser.open(url)
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        print("\ngrim_serve: stopped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
